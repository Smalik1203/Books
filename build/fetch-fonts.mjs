/* ============================================================
   Self-host the two book faces from Google Fonts.

     node build/fetch-fonts.mjs

   TWO faces, locked. Nothing else may be introduced:
     Spectral  — body, equations, diagram labels
     Vollkorn  — display: headings, component labels, captions

   Writes woff2 into fonts/ and regenerates css/fonts.css.
   Only latin and latin-ext subsets are kept.
   ============================================================ */

import { writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36';
const KEEP = new Set(['latin', 'latin-ext']);

const FAMILIES = [
  { slug: 'spectral', spec: 'Spectral:ital,wght@0,300;0,400;0,500;0,600;0,700;1,400;1,500;1,600' },
  { slug: 'vollkorn', spec: 'Vollkorn:ital,wght@0,500;0,600;0,700;1,500;1,600' },
];

await mkdir(`${ROOT}/fonts`, { recursive: true });
for (const f of await readdir(`${ROOT}/fonts`)) {
  if (f.endsWith('.woff2')) await unlink(`${ROOT}/fonts/${f}`);
}

let css = '/* Self-hosted book faces. Generated by build/fetch-fonts.mjs — do not edit. */\n\n';

for (const { slug, spec } of FAMILIES) {
  const sheet = await fetch(`https://fonts.googleapis.com/css2?family=${spec}&display=swap`,
    { headers: { 'User-Agent': UA } }).then(r => r.text());

  let kept = 0;
  for (const chunk of sheet.split('/*').slice(1)) {
    const subset = chunk.slice(0, chunk.indexOf('*/')).trim();
    if (!KEEP.has(subset)) continue;

    const block = '@font-face' + chunk.slice(chunk.indexOf('@font-face') + 10);
    const url = block.match(/https:\/\/fonts\.gstatic\.com[^)]*\.woff2/)?.[0];
    if (!url) continue;

    const weight = block.match(/font-weight:\s*(\d+)/)?.[1] ?? '400';
    const italic = /font-style:\s*italic/.test(block);
    const file = `${slug}-${weight}${italic ? 'i' : ''}-${subset}.woff2`;

    const buf = Buffer.from(await fetch(url, { headers: { 'User-Agent': UA } })
      .then(r => r.arrayBuffer()));
    await writeFile(`${ROOT}/fonts/${file}`, buf);

    css += block.replace(url, `../fonts/${file}`).trimEnd() + '\n\n';
    kept++;
  }
  console.log(`${slug}: ${kept} faces`);
}

await writeFile(`${ROOT}/css/fonts.css`, css);
console.log('wrote css/fonts.css');
