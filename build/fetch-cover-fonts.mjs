/* ============================================================
   Self-host the COVER faces from Google Fonts.

     node build/fetch-cover-fonts.mjs

   Deliberately separate from fetch-fonts.mjs, which owns the book's
   two locked faces and rewrites css/fonts.css wholesale. A cover is
   not a page: a jacket carrying its own display face while the text
   block keeps Spectral and Vollkorn is ordinary book practice, not a
   third face smuggled into the interior. Nothing here is reachable
   from a page — only css/cover-fonts.css links it, and only the
   cover shell links that.

   Writes woff2 into fonts/ prefixed cover-, and generates
   css/cover-fonts.css. Latin and latin-ext only.
   ============================================================ */

import { writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36';
const KEEP = new Set(['latin', 'latin-ext']);

/* One candidate per design direction. Whichever wins, delete the rest
   from this list and re-run — a cover ships with one face, not three. */
const FAMILIES = [
  { slug: 'archivo', spec: 'Archivo:wght@400;500;600;700;800;900' },
  { slug: 'grotesk', spec: 'Space+Grotesk:wght@400;500;600;700' },
  { slug: 'poppins', spec: 'Poppins:wght@400;500;600;700;800' },
];

await mkdir(`${ROOT}/fonts`, { recursive: true });
// Only the cover's own files are cleared. The book's faces are not ours.
for (const f of await readdir(`${ROOT}/fonts`)) {
  if (f.startsWith('cover-') && f.endsWith('.woff2')) await unlink(`${ROOT}/fonts/${f}`);
}

let css = '/* Self-hosted COVER faces. Generated by build/fetch-cover-fonts.mjs — do not edit.\n'
  + '   Linked only by the cover shell. The book\'s two faces live in fonts.css. */\n\n';

for (const { slug, spec } of FAMILIES) {
  const sheet = await fetch(`https://fonts.googleapis.com/css2?family=${spec}&display=swap`,
    { headers: { 'User-Agent': UA } }).then(r => r.text());

  let kept = 0;
  for (const chunk of sheet.split('/*').slice(1)) {
    const subset = chunk.slice(0, chunk.indexOf('*/')).trim();
    if (!KEEP.has(subset)) continue;

    const block = '@font-face' + chunk.slice(chunk.indexOf('@font-face') + 10);
    const url = block.match(/https:\/\/fonts\.gstatic\.com[^)]*\.woff2/)?.[0];
    if (!url) continue;

    const weight = block.match(/font-weight:\s*(\d+)/)?.[1] ?? '400';
    const file = `cover-${slug}-${weight}-${subset}.woff2`;

    const buf = Buffer.from(await fetch(url, { headers: { 'User-Agent': UA } })
      .then(r => r.arrayBuffer()));
    await writeFile(`${ROOT}/fonts/${file}`, buf);

    css += block.replace(url, `../fonts/${file}`).trimEnd() + '\n\n';
    kept++;
  }
  console.log(`${slug}: ${kept} faces`);
}

await writeFile(`${ROOT}/css/cover-fonts.css`, css);
console.log('→ css/cover-fonts.css');
