#!/usr/bin/env node
/* ============================================================
   Self-host the REFERENCE-DESIGN face from Google Fonts.

     node build/fetch-reference-fonts.mjs

   The third of three font fetchers, and it exists because the
   reference chapters were reading the cover's files.

   fetch-fonts.mjs owns the book's two locked faces. fetch-cover-
   fonts.mjs owns the jacket's, and says in its own header that
   nothing under pages/ may reach them — then clears every
   cover-*.woff2 on each run and invites you to delete the losing
   families from its list once a jacket is settled. Both class-6
   reference chapters were pointing at cover-poppins-400-latin.woff2
   and cover-poppins-700-latin.woff2, so the day a cover settles on
   Archivo, thirty-three printed pages fall back to Arial.

   The other half of the reason is the italic. The cover fetcher
   asks for wght only, so no italic file was ever downloaded, and
   .science-italic was being drawn by shearing the upright — which
   on a geometric face turns every circular bowl into an ellipse.
   Six words in chapter 1 were set that way.

   Writes woff2 into fonts/ prefixed reference-, and generates
   css/reference-fonts.css. Latin and latin-ext. Poppins carries a
   devanagari subset too; add it to KEEP the day a page needs one.
   ============================================================ */

import { writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36';
const KEEP = new Set(['latin', 'latin-ext']);

/* Upright and italic, at the two weights the reference components
   use: .food-text is 400 and .food-bold is 700. A weight nothing
   sets is a file nothing loads. */
const FAMILY = { slug: 'poppins', spec: 'Poppins:ital,wght@0,400;0,700;1,400;1,700' };

await mkdir(`${ROOT}/fonts`, { recursive: true });
// Only this fetcher's own files. The book's and the cover's are not ours.
for (const f of await readdir(`${ROOT}/fonts`)) {
  if (f.startsWith('reference-') && f.endsWith('.woff2')) await unlink(`${ROOT}/fonts/${f}`);
}

let css = '/* Self-hosted REFERENCE faces. Generated by build/fetch-reference-fonts.mjs — do not edit.\n'
  + '   Linked by the food-reference and science-reference designs. The book\'s two faces\n'
  + '   live in fonts.css; the jacket\'s in cover-fonts.css. Nothing here is shared with\n'
  + '   either, so a cover changing face cannot unset a printed page. */\n\n';

/* display: block, not swap. A proof is a picture of a printed page:
   a first frame set in Arial is a wrong measurement, not a fast one. */
const sheet = await fetch(
  `https://fonts.googleapis.com/css2?family=${FAMILY.spec}&display=block`,
  { headers: { 'User-Agent': UA } }).then(r => r.text());

let kept = 0;
for (const chunk of sheet.split('/*').slice(1)) {
  const subset = chunk.slice(0, chunk.indexOf('*/')).trim();
  if (!KEEP.has(subset)) continue;

  const block = '@font-face' + chunk.slice(chunk.indexOf('@font-face') + 10);
  const url = block.match(/https:\/\/fonts\.gstatic\.com[^)]*\.woff2/)?.[0];
  if (!url) continue;

  const weight = block.match(/font-weight:\s*(\d+)/)?.[1] ?? '400';
  const italic = /font-style:\s*italic/.test(block);
  const file = `reference-${FAMILY.slug}-${weight}${italic ? 'i' : ''}-${subset}.woff2`;

  const buf = Buffer.from(await fetch(url, { headers: { 'User-Agent': UA } })
    .then(r => r.arrayBuffer()));
  await writeFile(`${ROOT}/fonts/${file}`, buf);

  /* The pages name the family "Food Poppins", not "Poppins" — the
     reference designs were built against that name and it keeps the
     jacket's Poppins and this one from colliding in one document. */
  css += block.replace(url, `../fonts/${file}`)
    .replace(/font-family:\s*'Poppins'/, "font-family: 'Food Poppins'")
    .trimEnd() + '\n\n';
  kept++;
}

if (kept < 8) {
  console.error(`Only ${kept} faces kept — expected 8 (400/700, upright and italic, latin and latin-ext).`);
  console.error('css/reference-fonts.css not written; the existing one still stands.');
  process.exit(1);
}

await writeFile(`${ROOT}/css/reference-fonts.css`, css);
console.log(`${FAMILY.slug}: ${kept} faces`);
console.log('→ css/reference-fonts.css');
